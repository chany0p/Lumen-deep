// Lumen Deep — small seeded RNG (mulberry32) plus helpers. The game runs
// unseeded in normal play; the screenshot modes pass a fixed seed so a
// render is reproducible frame for frame.
export function makeRng(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// A throwaway RNG seeded from time and Math.random for live play.
export function liveRng() {
  return makeRng((Date.now() ^ (Math.random() * 0xffffffff)) >>> 0);
}

export function range(rng, min, max) {
  return min + rng() * (max - min);
}

export function pick(rng, list) {
  return list[Math.floor(rng() * list.length)];
}

export function clamp(value, min, max) {
  return value < min ? min : value > max ? max : value;
}

export function lerp(a, b, t) {
  return a + (b - a) * t;
}
